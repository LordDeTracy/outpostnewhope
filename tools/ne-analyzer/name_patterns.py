def strip(e):
    return e.split("_", 1)[1] if e.startswith("sub_") else e.split("@")[-1]


def building_rows(funcs, vts):
    """Building classes: ctor (type, owner), load ctor (), and the slots the class overrides."""
    groups = {}
    for r in json.load(open(os.path.join(catalog.ROOT, "reference", "outpost-exe", "building-classes.json"))):
        groups.setdefault(r["ctor"], []).append(r["name"])
    base = [strip(e) for e in vts["s6:CF6A"]["entries"][:26]]
    rows = [("s6:CF44", "Building::scalar_dtor", "base building deleting destructor")]
    for i, a in enumerate(base[1:], 1):
        rows.append((a, f"Building::{SLOTS[i]}", f"base vslot {i}: {SLOT_NOTE.get(SLOTS[i], '')}".strip()))
    used = {}
    for v in vts.values():
        for c in v["ctors"]:
            used.setdefault(strip(c), []).append(v["vtable"])
    overrides = {}
    for ctor, types in groups.items():
        cls = CLASS.get(ctor, types[0])
        if ctor == "s6:B39E":
            continue
        rows.append((ctor, f"{cls}::{cls}", "building class ctor (type, owner): " + "/".join(types)))
        vt = None
        seg = int(ctor[1:ctor.index(":")])
        lines = catalog.listing(seg).get(ctor, [])
        v = ctor_vtable(lines)
        if v is not None:
            vt = vts.get(f"s{seg}:{v:04X}")
        if not vt:
            continue
        for a2, vtl in used.items():
            if vt["vtable"] in vtl and a2 != ctor:
                calls = funcs.get(a2, {}).get("callers", [])
                if any(c.endswith("s7:0000") for c in calls):
                    rows.append((a2, f"{cls}::{cls}()", "building class ctor for loading (no arguments)"))
        for i, e in enumerate(vt["entries"][:26]):
            a2 = strip(e)
            if i < len(base) and a2 == base[i]:
                continue
            overrides.setdefault((a2, i), []).append(cls)
    for (a2, i), classes in overrides.items():
        nm = SLOTS[i] if i < len(SLOTS) else f"vslot{i}"
        note = SLOT_NOTE.get(nm, "")
        if len(classes) == 1:
            rows.append((a2, f"{classes[0]}::{nm}", f"vslot {i} override: {note}".strip(" :")))
        else:
            owner = "Robot" if all(c.startswith("Robo") for c in classes) else classes[0] + "Family"
            rows.append((a2, f"{owner}::{nm}", f"vslot {i}, shared by {'/'.join(classes)}: {note}".strip(" :")))
    return rows


