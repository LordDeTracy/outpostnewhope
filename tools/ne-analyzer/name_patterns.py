"""Names repetitive class families from their constructor arguments, plus their destructors.

Usage: python name_patterns.py  -> names/seg00_auto.tsv (hand-written names/segNN.tsv files override it)

Families:
  movie views   ctors s4:6D02..s4:7D70 call MovieView::MovieView (s4:6A0E) with
                push (next << 16 | movie), push (mode << 16 | sound)
  story pages   ctors s4:C958..s4:CF74 call StoryPage::StoryPage (s4:C402) with
                push (time << 16 | mode) after the picture/voice pair
Each class's vtable (installed by its ctor) has its deleting destructor in slot 0.
  buildings     every building class (reference/outpost-exe/building-classes.json): its two
                constructors and the methods its vtable overrides, by the base slot names
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import catalog  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))


def ctor_vtable(lines):
    """The vtable a ctor installs last: mov word ptr es:[bx], 0xVVVV before the SEGMENT store."""
    vt = None
    for l in lines:
        m = re.search(r"mov word ptr es:\[bx\], 0x([0-9a-f]+)\s*(;|$)", l)
        if m:
            vt = int(m.group(1), 16)
    return vt


def pushes(lines):
    out = []
    for l in lines:
        m = re.search(r"push 0x([0-9a-f]+)\s*(;|$)", l)
        if m and "66" in l.split()[1][:2]:
            out.append(int(m.group(1), 16))
    return out


def main():
    funcs = catalog.load_functions()
    lst = catalog.listing(4)
    vts = {v["vtable"]: v for v in json.load(open(os.path.join(catalog.DIS, "vtables.json")))}
    rows = []

    def slot0(vt):
        v = vts.get(f"s4:{vt:04X}")
        if not v or not v["entries"]:
            return None
        e = v["entries"][0]
        return e.split("_", 1)[1] if e.startswith("sub_") else e.split("@")[-1]

    for a, lines in sorted(lst.items(), key=lambda x: catalog.key(x[0])):
        body = "\n".join(lines)
        if a.startswith("s4:") and "call 0x6a0e" in body and a != "s4:6A0E":
            p = pushes(lines)
            if len(p) >= 2:
                movie, nxt = p[0] & 0xFFFF, p[0] >> 16
                sound, mode = p[1] & 0xFFFF, p[1] >> 16
                cls = f"MovieView{mode}"
                rows.append((a, f"{cls}::{cls}", f"movie view, mode {mode}: movie {movie}, then command {nxt}"
                             + (f", sound {sound}" if sound else "")))
                d = slot0(ctor_vtable(lines))
                if d:
                    rows.append((d, f"{cls}::scalar_dtor", f"mode {mode} movie view deleting destructor"))
        elif a.startswith("s4:") and "call 0xc402" in body and a != "s4:C402":
            p = pushes(lines)
            if len(p) >= 4:
                mode = p[2] & 0xFFFF
                ms = p[2] >> 16
                pic, nxt = p[0] & 0xFFFF, p[0] >> 16
                voice = p[1] >> 16
                cls = f"StoryPage{mode}"
                rows.append((a, f"{cls}::{cls}", f"story page, mode {mode}: picture {pic}, voice {voice}, "
                             f"{ms} ms, then command {nxt}"))
                d = slot0(ctor_vtable(lines))
                if d:
                    rows.append((d, f"{cls}::scalar_dtor", f"mode {mode} story page deleting destructor"))
    rows += building_rows(funcs, vts)
    seen = set()
    with open(os.path.join(HERE, "names", "seg00_auto.tsv"), "w", encoding="utf-8") as f:
        f.write("# Generated by name_patterns.py (movie views, story pages, building classes).\n"
                "# Hand-written names/segNN.tsv entries override these.\n")
        for a, n, p in rows:
            if a in seen or a not in funcs:
                continue
            seen.add(a)
            f.write(f"{a}\t{n}\t{p}\n")
    print(len(seen), "names")


